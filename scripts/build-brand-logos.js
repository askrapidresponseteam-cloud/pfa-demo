#!/usr/bin/env node
'use strict';
/* Writes assets/brand-logos.js from whatever is in img/brands/, so the shop
   knows which brands have a local logo without asking for thirty files that
   may not exist. Keyed by the seller's collection handle, which is the file
   name. Runs at deploy (from scripts/build-catalog.js) and as
   `npm run build:logos`. Never fails a build: an unreadable folder means an
   empty map, and the band falls back to the seller's collection images. */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'img', 'brands');
const OUT = path.join(ROOT, 'assets', 'brand-logos.js');
const TYPES = ['.svg', '.png', '.webp', '.jpg', '.jpeg'];

function buildBrandLogos() {
  const map = {};
  let files = [];
  try { files = fs.readdirSync(DIR); } catch (_) { files = []; }
  files.sort().forEach((file) => {
    const rawExt = path.extname(file);
    const ext = rawExt.toLowerCase();
    const handle = path.basename(file, rawExt).toLowerCase();
    if (!TYPES.includes(ext) || !/^[a-z0-9-]+$/.test(handle)) return;
    /* First type in TYPES order wins when the same handle exists twice. */
    if (map[handle] && TYPES.indexOf(path.extname(map[handle]).toLowerCase()) <= TYPES.indexOf(ext)) return;
    map[handle] = `/img/brands/${file}`;
  });
  const body = '/* Generated by scripts/build-brand-logos.js from img/brands/. Do not edit. */\n' +
    'window.PFA_BRAND_LOGOS=' + JSON.stringify(map) + ';\n';
  fs.writeFileSync(OUT, body);
  return map;
}

if (require.main === module) {
  const map = buildBrandLogos();
  console.log(`brand logos: ${Object.keys(map).length} -> assets/brand-logos.js`);
}
module.exports = buildBrandLogos;
